describe("the default keymap, in full", () => {
  it("has exactly 10-keymap.md's bindings and words", () => {
    const rows = DEFAULT_KEYMAP.map(
      (b) =>
        `${b.scope} | ${b.keys} | ${b.command} | ${b.desc}${b.modes ? ` | ${b.modes.join(",")}` : ""}${b.arg !== undefined ? ` | arg ${b.arg}` : ""}`,
    );
    expect(rows).toEqual(TABLE);
  });
});

describe("trimVimKeys, in full", () => {
  it("drops exactly the Vim keys outside the subset, each in its context", () => {
    const dropped: string[] = [];
    const api: VimKeyApi = {
      unmap: (lhs, ctx) => dropped.push(ctx ? `${lhs} ${ctx}` : lhs),
      mapCommand: () => {},
    };
    trimVimKeys(api);
    expect(dropped).toEqual(DROPPED);
  });
});
